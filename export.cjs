/* Compile one acknowledged, on-board preset into a small Windows runner; never flash firmware. */
'use strict';

const fs = require('node:fs/promises');
const path = require('node:path');
const os = require('node:os');
const crypto = require('node:crypto');
const {execFile} = require('node:child_process');
const {promisify} = require('node:util');

const AL65 = Object.freeze({model:'yunzii-al65', vendorId:0x4D4B, productId:0x3068, usagePage:0xFF60, usage:0x61,
  reportLength:32, channel:3, definitionVersion:'AL65_QMK_V0101_20241025'});
const BUILTIN_EFFECTS = Object.freeze({
  'rainbow-road': {id:7, name:'Rainbow Moving Chevron'},
  matrix: {id:15, name:'Digital Rain'},
  ghost: {id:0, name:'All Off'},
  'subtle-keywords': {id:1, name:'Solid Color'},
  solid: {id:1, name:'Solid Color'}
});
const LIMITATIONS = Object.freeze([
  'This exports an AL65 built-in whole-board effect, not the exact Lighting Lab preview.',
  'Keyword keys, protected anchors, mouse sync, layered reactions, custom layout, and Minimalist are not copied to AL65 firmware.',
  'Connect the AL65 directly by USB in wired mode. Bluetooth and the 2.4 GHz receiver are not supported.',
  'The runner uses Windows .NET Framework 4.x and the Windows HID driver; it needs no Lighting Lab, VIA, Node, or vendor app.',
  'Export defaults to 80% brightness and maximum firmware speed; the app speed slider uses a different scale and is preserved only in the embedded setup.',
  'Firmware Save is requested and verified in the current session; retention after USB power loss still needs an AL65 hardware test.'
]);

function exportError(message, code='EXPORT_UNSUPPORTED') {
  return Object.assign(new Error(message), {code, statusCode:422});
}

/** Return capability evidence for the chosen target, without probing or modifying a keyboard. */
function getExportCapabilities(model, selection={}) {
  model = String(model || 'standard-full-size').toLowerCase();
  if (typeof selection === 'string') selection = {effect:selection};
  const base = {model, executable:false, supported:false, mode:'unsupported', exact:false,
    needsApproximationAcknowledgement:false, supportedEffects:[], mappedEffect:null, limitations:[]};
  if (model !== AL65.model) {
    if(model==='auto'||model.startsWith('razer-'))return{...base,executable:true,supported:true,mode:'portable-sdk',exact:!['razer-ornata-v3','razer-ornata-v3-x'].includes(model),
      supportedEffects:[...require('./effects.js').EFFECTS],reason:'Auto-detecting Windows preset player: Razer keyboard + installed Chroma runtime. No Lighting Lab or Node installation is needed.',
      limitations:['Animated lighting runs while the preset is open; closing it releases control to Synapse.','Backgrounds repeat a baked animation sequence generated by the same renderer as the preview.','Keyboard reactions are opt-in and use key identities only in memory.','Unknown brands are reported as unsupported, without sending guessed USB instructions.','AL65 needs its separately acknowledged built-in firmware preset.']};
    const razer = model.startsWith('razer-');
    return {...base, reason:razer ?
      'This Razer model needs a compatible Chroma/Synapse runtime for custom lighting; a driver-free, persistent preset executable is not implemented. Save JSON or a native Chroma profile instead.' :
      'No verified standalone lighting protocol is available for this target. Save JSON, or choose YUNZII AL65 for its built-in firmware export.'};
  }
  const effect = selection.effect || 'rainbow-road';
  const mappedEffect = Object.hasOwn(BUILTIN_EFFECTS,effect) ? BUILTIN_EFFECTS[effect] : null;
  const supported = Boolean(mappedEffect);
  return {...base, executable:supported, supported, mode:'onboard-via',
    needsApproximationAcknowledgement:true, supportedEffects:Object.keys(BUILTIN_EFFECTS), mappedEffect,
    target:AL65, limitations:[...LIMITATIONS], reason:supported ?
      `AL65 built-in ${mappedEffect.name}; acknowledge the whole-board approximation before downloading.` :
      `The AL65 definition has no built-in equivalent for ${effect}. Choose Rainbow Road, Matrix, Ghost, Subtle Keywords, or Solid Color for a whole-board approximation.`};
}

function byte(value, fallback, name) {
  if (value === undefined) return fallback;
  if (!Number.isInteger(value) || value < 0 || value > 255) throw exportError(`${name} must be an integer from 0 to 255.`, 'EXPORT_INVALID');
  return value;
}

/** VIA color is hue/saturation; brightness remains a separately documented firmware control. */
function firmwareColor(selection) {
  const selected = selection.color ?? selection.keywordColor ?? selection.anchorColor ?? '#ff0033';
  if (typeof selected !== 'string' || !/^#[\da-f]{6}$/i.test(selected)) throw exportError('Export color must be a six-digit hex color.', 'EXPORT_INVALID');
  const [r,g,b] = [1,3,5].map(offset=>parseInt(selected.slice(offset,offset+2),16)/255);
  const max = Math.max(r,g,b), min = Math.min(r,g,b), delta = max-min;
  const degrees = delta===0 ? 0 : max===r ? 60*((g-b)/delta%6) : max===g ? 60*((b-r)/delta+2) : 60*((r-g)/delta+4);
  return {hue:Math.round(((degrees+360)%360)*255/360), saturation:max===0 ? 0 : Math.round(delta/max*255)};
}

/** Preserve the complete requested setup separately from the explicitly reduced firmware settings. */
function createExportManifest(selection, {targetModel, acceptApproximation=false, now=new Date()}={}) {
  if (!selection || typeof selection !== 'object' || Array.isArray(selection)) throw exportError('Choose a lighting setup to export.', 'EXPORT_INVALID');
  const serialized = JSON.stringify(selection);
  if (Buffer.byteLength(serialized) > 65536) throw exportError('The setup exceeds the 64 KiB export limit.', 'EXPORT_INVALID');
  const capabilities = getExportCapabilities(targetModel || selection.keyboardModel, selection);
  if(capabilities.mode==='portable-sdk')throw exportError('This manifest describes AL65 firmware only. Use the portable SDK player for Razer keyboards.');
  if (!capabilities.supported) throw exportError(capabilities.reason);
  if (acceptApproximation !== true) throw exportError('Acknowledge the AL65 whole-board approximation before generating this executable. Your exact per-key selection cannot be stored through the documented AL65 controls.', 'EXPORT_APPROXIMATION_REQUIRED');
  const options = selection.portable || {};
  const color = firmwareColor(selection);
  return {schemaVersion:1, product:'Lighting Lab preset', generatedAt:now.toISOString(), target:AL65,
    requested:JSON.parse(serialized), capabilities, approximationAcknowledged:true,
    desired:{brightness:byte(options.brightness,204,'Portable brightness'), mode:capabilities.mappedEffect.id,
      speed:byte(options.speed,255,'Portable speed'), hue:byte(options.hue,selection.effect === 'matrix' ? 85 : color.hue,'Portable hue'),
      saturation:byte(options.saturation,selection.effect === 'matrix' ? 255 : color.saturation,'Portable saturation')},
    settingReduction:{brightness:'80% by default; portable.brightness overrides on firmware scale 0-255.',
      speed:'Maximum firmware speed by default; host animation multiplier is preserved but has no verified firmware equivalent.',
      color:selection.effect==='matrix'?'Digital Rain uses green by default.':'Selected hue and saturation are copied; brightness is a separate control.'},
    operation:'Read original lighting; write backup; apply built-in mode; verify; save channel 3; verify; exit.',
    restore:'Run the same executable with --restore <backup.json>, or use its on-screen restore command.'};
}

/** Compile trusted source with an embedded JSON resource; user input never becomes C# or shell text. */
async function createPresetExecutable(selection, options={}) {
  const target=options.targetModel||selection.keyboardModel;
  let manifest;
  if(target===AL65.model)manifest=createExportManifest(selection,options);
  else{
    const {validateSelection,createCustomMouseFrame}=require('./lighting-domain.cjs'),Plan=require('./core.js'),Effects=require('./effects.js');
    const normalized=validateSelection(selection),full={...selection,...normalized};
    const capabilities=getExportCapabilities(target||'auto',full);
    if(!capabilities.supported)throw exportError(capabilities.reason);
    const frameMs=46,frameCount=128,layout=Plan.layoutForModel(full.keyboardModel,full.customLayout);
    const virtualKeys={ESC:27,BACKSPACE:8,TAB:9,CAPS:20,ENTER:13,SPACE:32,LCTRL:162,RCTRL:163,LSHIFT:160,RSHIFT:161,LALT:164,RALT:165,LWIN:91,RWIN:92,MENU:93,INSERT:45,DEL:46,HOME:36,END:35,PGUP:33,PGDN:34,UP:38,DOWN:40,LEFT:37,RIGHT:39,NUM_LOCK:144,NUM_DECIMAL:110,NUM_ADD:107,NUM_SUBTRACT:109,NUM_MULTIPLY:106,NUM_DIVIDE:111,'`':192,'-':189,'=':187,'[':219,']':221,'\\':220,';':186,"'":222,',':188,'.':190,'/':191};
    const keys=layout.keys.map(key=>{const coordinate=Plan.chromaCoordinates[key.id];let vk=virtualKeys[key.id]||0;if(/^[A-Z0-9]$/.test(key.id))vk=key.id.charCodeAt(0);if(/^NUM_[0-9]$/.test(key.id))vk=96+Number(key.id.slice(4));if(/^F([1-9]|1[0-2])$/.test(key.id))vk=111+Number(key.id.slice(1));return{id:key.id,row:coordinate[0],col:coordinate[1],x:key.x+key.w/2,y:key.y,vk};});
    manifest={schemaVersion:2,product:'Lighting Lab portable preset',target:{model:'auto',supported:['razer-chroma','yunzii-al65']},requested:full,capabilities,
      playback:{frameMs,frames:Array.from({length:frameCount},(_,i)=>Effects.frame(full,i*frameMs)),keys}};
    if(full.mouseSync)manifest.playback.mouseFrames=Array.from({length:frameCount},(_,i)=>createCustomMouseFrame(full.effect,0,{...full,timeMs:i*frameMs}).param);
    if(options.acceptApproximation===true&&getExportCapabilities(AL65.model,full).supported)manifest.al65=createExportManifest(full,{targetModel:AL65.model,acceptApproximation:true});
  }
  const compilerPath = options.compilerPath || path.join(process.env.WINDIR || 'C:\\Windows', 'Microsoft.NET',
    process.arch === 'x64' ? 'Framework64' : 'Framework', 'v4.0.30319', 'csc.exe');
  const execFileImpl = options.execFileImpl || promisify(execFile);
  if (!options.execFileImpl && process.platform !== 'win32') throw exportError('Executable export currently builds on Windows. Save JSON on this server instead.', 'EXPORT_BUILD_UNAVAILABLE');
  const staging = await fs.mkdtemp(path.join(os.tmpdir(), 'lighting-lab-preset-'));
  try {
    const resource = path.join(staging,'preset.json');
    const executable = path.join(staging,'lighting-preset.exe');
    await fs.writeFile(resource, JSON.stringify(manifest));
    try {
      await execFileImpl(compilerPath, ['/nologo','/target:exe','/platform:anycpu','/optimize+',
        '/reference:System.Web.Extensions.dll',`/out:${executable}`,`/resource:${resource},preset.json`,
        path.join(__dirname,'portable','PhysicalInput.cs'),path.join(__dirname,'portable','ChromaPreset.cs'),path.join(__dirname,'portable','PresetRunner.cs')], {windowsHide:true,timeout:30000,maxBuffer:1024*1024});
    } catch (error) {
      throw exportError(`The preset executable could not be compiled: ${error.stdout || error.message}`, 'EXPORT_BUILD_FAILED');
    }
    const bytes = await fs.readFile(executable);
    if (bytes.length < 2 || bytes.toString('ascii',0,2) !== 'MZ') throw exportError('The compiler did not produce a Windows executable.', 'EXPORT_BUILD_FAILED');
    return {bytes, filename:`Lighting-Lab-${manifest.schemaVersion===2?'Auto':'AL65'}-${selection.effect}.exe`, manifest,
      capabilities:manifest.capabilities, sha256:crypto.createHash('sha256').update(bytes).digest('hex')};
  } finally {
    // The compiler owns this mkdtemp directory exclusively; no user paths are removed.
    await fs.rm(staging,{recursive:true,force:true});
  }
}

module.exports = {AL65, BUILTIN_EFFECTS, createExportManifest, createPresetExecutable, getExportCapabilities};
